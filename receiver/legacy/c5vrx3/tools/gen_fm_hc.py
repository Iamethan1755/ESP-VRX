#!/usr/bin/env python3
"""Generate the history-conditioned (HC) two-bundle demodulator.

Golden's two-stage shape with one change: the decoder lookup is addressed by
the endpoint raw byte PLUS the retained state's quadrant (O29..O30 -> address
bits 24..25), so 4 x 256 decoder entries use the whole 1024-word LUT:

  LUT[(quadrant << 8) | raw].bits[12:8] = MAP phase state given raw and the
                                          previous quadrant (trained)
  LUT[(prev << 5) | cur].bits[5:0]      = nominal Golden P20/G2 DAC code for
                                          the state step (unbiased; no
                                          content prior)

Training and scoring: tools/hc_estimator_bench.py (independent picture, seed
and carrier offset for scoring). Outputs main/fm_hc.bsasm and
main/fm_hc_lut.h (the same tables for CPU mirrors such as the sync flywheel).
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import hc_estimator_bench as bench  # noqa: E402

TARGET = ROOT / "main/fm_hc.bsasm"
HEADER = ROOT / "main/fm_hc_lut.h"
TRAIN_SEEDS = [11, 12]
TRAIN_RADII = [1.5, 2.0, 2.5, 3.0, 4.0, 5.5]
TRAIN_CFOS = [-3e5, 0.0, 4e5]
TRAIN_LINES = 40


def tables():
    est = bench.HCEstimator(mmse=False)
    est.train(bench.capture_set(TRAIN_SEEDS, 0, TRAIN_RADII, TRAIN_CFOS,
                                TRAIN_LINES))
    dec = [int(v) for v in est.dec]
    pair = [int(v) for v in est.pair_code]
    return dec, pair


def words(dec, pair):
    return [(dec[a] << 8) | pair[a] for a in range(1024)]


def build(dec, pair) -> str:
    golden = (ROOT / "main/fm.bsasm").read_text(encoding="utf-8")
    body = re.sub(r"(?m)^lut .*$", "lut " + " ".join(map(str, words(dec, pair))),
                  golden)
    old = "    set 24..25 L,\n    set 31 L,\n    read 16,"
    assert body.count(old) == 1
    body = body.replace(old, "    # History: decoder bank = retained state's quadrant.\n"
                             "    set 24 O29,\n    set 25 O30,\n"
                             "    set 31 L,\n    read 16,")
    header = """# History-conditioned (HC) two-bundle WBFM demodulator. Generated by
# tools/gen_fm_hc.py from Golden fm.bsasm; only the decoder bank differs:
#   LUT[(prev_quadrant<<8)|raw].bits[12:8] = MAP 5-bit phase state
#   LUT[(prev<<5)|cur].bits[5:0]           = nominal P20/G2 DAC code
# Offline bench (tools/hc_estimator_bench.py): ~40 % fewer FM clicks than
# Phase8 at C/N 5-12 dB (about 1.5-2 dB threshold), beats Golden throughout.
"""
    return header + body


def c_header(dec, pair) -> str:
    def arr(name, values):
        rows = [", ".join(f"{v:2d}" for v in values[i:i + 16])
                for i in range(0, len(values), 16)]
        return (f"static const unsigned char {name}[{len(values)}] = {{\n    "
                + ",\n    ".join(rows) + "\n};\n")
    return ("#pragma once\n/* Generated by tools/gen_fm_hc.py; must match "
            "main/fm_hc.bsasm. */\n"
            + arr("c5vrx_hc_decoder", dec) + arr("c5vrx_hc_pair_code", pair))


def main():
    dec, pair = tables()
    TARGET.write_text(build(dec, pair), encoding="utf-8")
    HEADER.write_text(c_header(dec, pair), encoding="utf-8")
    changed = sum(dec[a] != bench.P5[a & 255] for a in range(1024))
    print(f"wrote {TARGET.name}, {HEADER.name}; decoder entries differing "
          f"from Golden's static state: {changed}/1024")


if __name__ == "__main__":
    main()
