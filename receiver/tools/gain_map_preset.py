#!/usr/bin/env python3
# C5VRX-5 by Twotoz and the C5VRX contributors: build main/gain_map_preset.h
# from measured boards.
#
# On each board, fly or bench with the VTX on for a few minutes (Direct Gain
# learns its map only from a confirmed VTX), then press M on the console and
# save the log. Then:
#
#   python3 tools/gain_map_preset.py board1.log [board2.log ...] > main/gain_map_preset.h
#
# Every map is relative (any scale). Maps are aligned on the gain index they
# share most, and the preset holds the median ratio per index over all boards
# that measured it with confidence >= MIN_CONF. Indices nobody measured stay 0.
import re
import statistics
import sys

MIN_CONF = 2
LINE = re.compile(r"GAINMAP v=(\d+) max=(\d+) band5=(\d+).*?entries=\d+((?: \d+:\d+:\d+:\d+)*)")


def parse(path):
    maps = []
    with open(path, errors="replace") as f:
        for line in f:
            m = LINE.search(line)
            if not m:
                continue
            entries = {}
            for item in m.group(4).split():
                k, p, c, _ = (int(x) for x in item.split(":"))
                if c >= MIN_CONF and p:
                    entries[k] = p
            maps.append((int(m.group(2)), int(m.group(3)), entries))
    return maps[-1] if maps else None   # the newest map of the log


def main(argv):
    if len(argv) < 2:
        print("usage: gain_map_preset.py LOG [LOG ...] > main/gain_map_preset.h", file=sys.stderr)
        return 2
    boards = [b for b in (parse(p) for p in argv[1:]) if b and len(b[2]) > 1]
    if not boards:
        print("no GAINMAP line with learned entries found (press M after flying with the VTX on)", file=sys.stderr)
        return 1
    max_index, band5 = boards[0][0], boards[0][1]
    boards = [b for b in boards if b[0] == max_index and b[1] == band5]
    counts = {}
    for _, _, e in boards:
        for k in e:
            counts[k] = counts.get(k, 0) + 1
    anchor = max(counts, key=lambda k: (counts[k], k))
    ratios = {}
    for _, _, e in boards:
        if anchor not in e:
            continue
        for k, p in e.items():
            ratios.setdefault(k, []).append(p * 1024.0 / e[anchor])
    table = [0] * (max_index + 1)
    for k, v in ratios.items():
        if k <= max_index:
            table[k] = max(1, min(65535, round(statistics.median(v))))
    used = sum(1 for b in boards if anchor in b[2])
    rows = ",\n".join("    " + ", ".join(f"{x:5d}" for x in table[i:i + 12]) for i in range(0, len(table), 12))
    print(f"""/* C5VRX-5 by Twotoz and the C5VRX contributors: built-in gain map preset.
 *
 * Generated by tools/gain_map_preset.py from {used} measured board(s),
 * aligned on gain index {anchor}, median ratio per index (Q10, any common
 * scale; 0 = unknown). Imported with the lowest confidence and a high
 * uncertainty; a board's own learning with a confirmed VTX replaces it. */
#pragma once
#include <stdint.h>

#define GAIN_MAP_PRESET_MAX_INDEX {max_index}u
#define GAIN_MAP_PRESET_BAND5     {band5}u
#define GAIN_MAP_PRESET_BOARDS    {used}u   /* boards the table was built from */
static const uint16_t c5vrx5_gain_map_preset_q10[GAIN_MAP_PRESET_MAX_INDEX + 1u] = {{
{rows}
}};""")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
