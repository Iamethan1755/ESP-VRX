"""U85Q-LP: U85Q with a post-detection low-pass in the same two bundles.
(C5VRX by Twotoz and the C5VRX contributors; extends U85Q, model
1a09f5c092e8 from PR #190, and the counter research of PRs #73/#74/#90 and
legacy/c5vrx4/RESEARCH.md.)

Why: FM detection noise rises with the video frequency, and the colour
subcarrier (PAL 4.43 / NTSC 3.58 MHz) sits where it is largest. A low-pass
after the detector trades sharpness and colour for less noise at the range
edge (research/README.md section 12).

What fits: per 50 ns span the TX BitScrambler has two bundles, both LUT16
lookups are used by U85Q and both opcode slots are free (U85Q uses nop).
In LUT16 mode only counter A can be routed next to LUT bits (B overlaps
the LUT mux region), the counter operand is output[31:16] (shared with the
LUT address output[25:16]) and one opcode per bundle. That leaves one
6-bit register y = A[15:10] with LOAD + ADD per span:

  controller: emit y (A[15:10]); look up raw IQ (as U85Q);
              LDCTIA: A = {y >> 1 at A[14:10], raw address bits below}
  worker:     emit y again (O[5:0]); look up (token, phase) (as U85Q);
              ADDCTIAH: A[15:8] += {x >> 1 at bits 30:26, phase bits 25:24}

so y <- (y >> 1) + (x >> 1): a one-pole IIR with pole 1/2 on the U85Q DAC
code x, one span of latency, the address bits below A[10] acting as dither.
No sum exceeds 8 bits. The LUT is the unchanged U85Q LUT; the controller
carries the phase state and x >> 1 to the worker in output bits 6..15
(bits 6, 7 of the written byte drive no DAC pin). Each bundle writes one
byte, so the stream is [y, y] per span as before.

Usage:
  python u85q_lp.py generate          write main/u85q_lp.bsasm
  python u85q_lp.py check             generated file current; bsasm emulator
                                      (ESP-IDF parse) == U85Q sim and LP model;
                                      live U85Q <-> LP switch converges
  python u85q_lp.py study [out.json]  picture model, U85Q vs U85Q-LP
Synthetic numbers (sim.py); not goggle acceptance or measured range.
"""
import json
import os
import sys
from functools import lru_cache
from pathlib import Path
import numpy as np
from numba import njit

HERE = Path(__file__).resolve().parent
MAIN = HERE.parent / 'main'
OUT = MAIN / 'u85q_lp.bsasm'
RAW_BITS = '4 5 6 7 0 1 2 3 15 11'.split()     # U85Q PAIR4411 address bits


def program():
    raw = ',\n'.join(f'    set {16 + k} {b}' for k, b in enumerate(RAW_BITS))
    controller = f"""    set 0..5 A10..A15,
    set 6..7 L4..L5,
    set 8..12 L6..L10,
    set 13..15 L1..L3,
{raw},
    set 26..30 A11..A15,
    set 31 L,
    read 16,
    write 8,
    ldctia"""
    worker = """    set 0..5 O0..O5,
    set 16..20 L11..L15,
    set 21..25 O8..O12,
    set 26..28 O13..O15,
    set 29..30 O6..O7,
    set 31 L,
    write 8,
    addctiah"""
    body = ''.join(f'controller_{k}:\n{controller}\nworker_{k}:\n{worker}\n' for k in range(4))
    return body


def generate(write=True):
    src = (MAIN / 'u85q.bsasm').read_text()
    lut = next(line for line in src.splitlines() if line.startswith('lut '))
    text = f"""# C5VRX by Twotoz/contributors: U85Q-LP, U85Q plus a post-detection IIR
# low-pass (pole 1/2) in counter A, same two bundles, same LUT.
# Generated by research/u85q_lp.py. The range-edge program of the kp + LP
# ladder (kp_ladder.h, K mode 2), swapped in live by transport_set_lp().
cfg prefetch true
cfg eof_on downstream
cfg trailing_bytes 0
cfg lut_width_bits 16
{program()}{lut}
"""
    if write:
        OUT.write_text(text)
        print(f'wrote {OUT}')
    return text


# ---- generic BitScrambler emulator (subset: set/read/write, LUT, counter
# loads/adds, nop; no jumps), driven by the ESP-IDF assembler's own parse.
@lru_cache(maxsize=1)
def _bsasm():
    idf = os.environ.get('IDF_PATH')
    if not idf:
        raise SystemExit('set IDF_PATH (ESP-IDF v6.0.x) for tools/bsasm.py')
    sys.path.insert(0, str(Path(idf) / 'tools'))
    import bsasm
    return bsasm


def assemble(path):
    bs = _bsasm()
    cfg = json.loads((Path(os.environ['IDF_PATH']) / 'components/esp_driver_bitscrambler/bsasm_targets/esp32c5.json').read_text())
    insts, meta, lut = bs.bsasm_assemble(bs.bsasm_parse(Path(path).read_text()), cfg)
    return insts, meta, lut


def emulate(path, data, n_out, switch_to=None, switch_at=-1):
    """Runs the program over `data` (bytes); returns the first n_out output
    bytes. With switch_to, the instruction memory is replaced by that
    program's instructions after `switch_at` executed bundles, keeping the
    PC, registers, counters and LUT: the firmware's paused live rewrite."""
    insts, meta, lut = assemble(path)
    other = assemble(switch_to)[0] if switch_to else None
    executed = 0
    if meta['lut_width_bits'] != 16:
        raise ValueError('emulator models LUT16 only')
    lut = [v & 0xffff for v in lut]
    stream = iter(data)

    def take(nbits):
        v = 0
        for k in range(nbits // 8):
            v |= next(stream) << (8 * k)
        return v
    reg = 0
    for _ in range(4):                      # cfg prefetch true: 64 bits
        reg = (reg >> 16) | (take(16) << 48)
    out_prev, lut_out, ctr, pc, emitted = 0, 0, [0, 0], 0, bytearray()
    while len(emitted) < n_out:
        inst = insts[pc]
        flags = {}
        for src in inst['mux'].values():
            flags.update({k: v for k, v in src.get('flags', {}).items() if k != 'rel_addr'})
        out = 0
        for bit, src in inst['mux'].items():
            i = src['muxsel']
            if i < 32:
                v = reg >> i
            elif i < 64:
                if flags.get('lutsel') and i >= 48:
                    v = lut_out >> (i - 48)
                elif flags.get('ctrsel'):
                    v = ctr[(i - 32) // 16] >> ((i - 32) % 16)
                else:
                    v = reg >> i
            elif i == 94:
                v = 0
            elif i == 95:
                v = 1
            elif 96 <= i < 128:
                v = out_prev >> (i - 96)
            else:
                raise ValueError(f'source {i} not modelled')
            out |= (v & 1) << bit
        op = inst.get('op', {'op': None})
        operand = out >> 16
        c = op.get('c', 0)
        if op['op'] in (bsasm_op('LDCTI'), bsasm_op('ADDCTI')):
            add = op['op'] == bsasm_op('ADDCTI')
            old = ctr[c]
            hi = ((old >> 8) + (operand >> 8) if add else operand >> 8) & 255
            lo = ((old & 255) + (operand & 255) if add else operand & 255) & 255
            if op['h'] and op['l']:
                new = ((old + operand) if add else operand) & 0xffff
            else:
                new = ((hi << 8) | (old & 255)) if op['h'] else ((old & 0xff00) | lo)
            ctr[c] = new
        elif op['op'] is not None and op['op'] != bsasm_op('ADD'):
            raise ValueError('opcode not modelled')
        elif op['op'] == bsasm_op('ADD') and op.get('ctr_add'):
            raise ValueError('ADD with a value not modelled')
        w = inst.get('write', 0)
        emitted += (out & ((1 << w) - 1)).to_bytes(4, 'little')[:w // 8]
        r = inst.get('read', 0)
        if r:
            reg = (reg >> r) | (take(r) << (64 - r))
        lut_out = lut[(out >> 16) & 1023]       # LUT16: address output[25:16]
        out_prev = out
        pc = (pc + 1) % len(insts)
        executed += 1
        if other is not None and executed == switch_at:
            insts = other
    return bytes(emitted[:n_out])


def check_switch(n=12000, seed=197):
    """Live program switch U85Q <-> U85Q-LP in the emulator: the output after
    the switch must converge to the target program's steady output."""
    sys.path.insert(0, str(HERE))
    import sim
    c = sim.make_case(seed, 6.0, 'PAL', 1.0, filter_hz=12e6, fields=1)
    raw = c['raw'][:2 * n].tobytes()
    u, lp = MAIN / 'u85q.bsasm', OUT
    ok = True
    for a, b, name in ((u, lp, 'U85Q -> LP'), (lp, u, 'LP -> U85Q')):
        steady = np.frombuffer(emulate(b, raw, 2 * n - 64), np.uint8) & 63
        for at in (4001, 4002, 4003, 4004):         # every slot: controller/worker, both bundle phases
            got = np.frombuffer(emulate(a, raw, 2 * n - 64, switch_to=b, switch_at=at), np.uint8) & 63
            # Switching before a worker emits 24 or 8 bits in that span (the
            # programs split their 16 bits per span differently): the DAC
            # stream moves by one byte (25 ns). Compare at that shift.
            best = None
            for shift in (-1, 0, 1):
                g = got[at + 64:len(got) - 2]
                s = steady[at + 64 + shift:len(got) - 2 + shift]
                miss = int(np.sum(g != s))
                if best is None or miss < best[1]:
                    best = (shift, miss)
            shift = best[0]
            g, s = got[at:len(got) - 2], steady[at + shift:len(got) - 2 + shift]
            bad = np.flatnonzero(g != s)
            last = int(bad[-1]) + 1 if len(bad) else 0
            ok &= last <= 64
            print(f'{name}, switch after bundle {at}: stream shift {shift:+d} byte, {len(bad)} bytes differ, '
                  f'equal to steady from byte {last} after the switch')
    return ok


def bsasm_op(name):
    return getattr(_bsasm(), 'OP_' + name)


# ---- arithmetic model of U85Q-LP (numba), checked against the emulator
@njit(cache=True)
def lp_codes(raw, lut):
    bits = np.array([4, 5, 6, 7, 0, 1, 2, 3, 15, 11], np.int64)
    out = np.zeros(len(raw), np.uint8)
    state = 0
    x = 0
    a = 0
    n = len(raw) // 2 - 4
    for k in range(n):
        word = np.int64(raw[2 * k]) | (np.int64(raw[2 * k + 1]) << 8)
        y = (a >> 10) & 63
        out[2 * k] = y
        out[2 * k + 1] = y
        address = 0
        for j in range(10):
            address |= ((word >> bits[j]) & 1) << j
        # controller: LDCTIA, A = {0, y>>1, raw address}
        a = ((y >> 1) << 10) | address
        token = np.int64(lut[address]) >> 11
        # worker: ADDCTIAH, A[15:8] += {0, x>>1, phase bits 4:3}
        hi = ((a >> 8) + (((x >> 1) << 2) | (state >> 3))) & 255
        a = (hi << 8) | (a & 255)
        value = np.int64(lut[(state << 5) + token])
        x = value & 63
        state = (value >> 6) & 31
    return out


def check(n=20000, seed=196):
    sys.path.insert(0, str(HERE))
    import sim
    if OUT.read_text() != generate(write=False):
        print(f'{OUT} is stale: run python u85q_lp.py generate')
        return False
    rng = np.random.default_rng(seed)
    c = sim.make_case(seed, 4.0, 'PAL', 1.0, filter_hz=12e6, fields=1)
    raw = np.concatenate([c['raw'][:n], rng.integers(0, 256, n, dtype=np.uint8)])
    lut = sim.u85q_lut()
    got = np.frombuffer(emulate(OUT, raw.tobytes(), 2 * len(raw) // 2 - 64), np.uint8)
    ref = lp_codes(raw, lut)[:len(got)]
    bad = np.flatnonzero((got[:len(ref)] & 63) != ref)
    # U85Q itself under the same emulator, against sim.u85q_codes.
    u = np.frombuffer(emulate(MAIN / 'u85q.bsasm', raw.tobytes(), len(raw) - 64), np.uint8)
    uref = sim.u85q_codes(raw)
    shift = next(s for s in range(8) if np.array_equal(u[s:s + 4000] & 63, uref[:4000]))
    ubad = np.flatnonzero((u[shift:shift + len(uref) - 64] & 63) != uref[:len(uref) - 64][:len(u) - shift])
    print(f'U85Q emulator vs sim.u85q_codes: offset {shift} bytes, {len(ubad)} mismatches')
    print(f'U85Q-LP emulator vs lp_codes: {len(bad)} mismatches in {len(got)} bytes')
    return not len(bad) and not len(ubad)


def study(out_path=None):
    sys.path.insert(0, str(HERE))
    import sim
    lut = sim.u85q_lut()
    rows = []
    cnrs = [float(x) for x in os.environ.get('CNRS', '-1,0,1,2,3,4,6,8,10,12,14,20,30').split(',')]
    for dev in (1.0, 1.4):
        for cnr in cnrs:
            r = {'deviation': dev, 'cnr': cnr}
            for name, f in (('u85q', sim.u85q_codes), ('u85q_lp', lambda raw: lp_codes(raw, lut))):
                s, p = [], []
                for seed in (11, 12, 13, 14):
                    c = sim.make_case(1000 * seed + int(10 * cnr) + 7, cnr, ('PAL', 'NTSC')[seed % 2], dev,
                                      filter_hz=12e6, fields=1)
                    m = sim.measure(c, f(c['raw']), f(c['clean']))
                    s.append(m['sinad'])
                    p.append(m['picture'])
                r[name] = {'sinad': float(np.mean(s)), 'picture': float(np.mean(p))}
            rows.append(r)
            print(f"dev {dev} C/N {cnr:5.1f}: U85Q SINAD {r['u85q']['sinad']:6.2f} lock {r['u85q']['picture']:.2f}"
                  f" | U85Q-LP SINAD {r['u85q_lp']['sinad']:6.2f} lock {r['u85q_lp']['picture']:.2f}", flush=True)
    if out_path:
        Path(out_path).write_text(json.dumps(rows, indent=1))
    return rows


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'generate':
        generate()
    elif cmd == 'check':
        sys.exit(0 if check() and check_switch() else 1)
    elif cmd == 'study':
        study(sys.argv[2] if len(sys.argv) > 2 else None)
    else:
        print(__doc__)
        sys.exit(2)
