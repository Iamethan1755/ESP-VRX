"""U85Q kp tables and an ideal live-morph research model.
(C5VRX by Twotoz and the C5VRX contributors; the LUT formula is the C5VRX-4
untrained generator of PR #190, `v4/tools/dsp_search/untrained_search.py`
build() at bce63fd, reduced to the U85Q parameter set.)

Why the ideal arithmetic model can morph:
- u85q.bsasm, u85q_kp060 and u85q_kp050 are the same program; only the LUT
  differs. Their token bits (the raw -> phase observation, top 5 bits of
  every shared word) are identical, and the 32 phase states mean the same
  angles. Only the (phase, token) -> (next phase, DAC) half changes.
- So every LUT word is self-consistent in either table. A table in the
  middle of a rewrite is a valid tracker whose kp differs per entry, and the
  tracker state carries over unchanged in that model.
- The ESP32-C5 LUT port writes one entry per register write in the
  execution width (TX_LUT_CFG0.lut_mode = 1: 2-byte entries, lut_idx =
  entry). Unlike bitscrambler_load_lut(), which switches the width to 32
  bit while it writes, this never changes how the running program reads
  the LUT. Whether a CPU write can collide with a BitScrambler read in the
  same cycle is a hardware question: RUN/PAUSE writes failed physical
  verification on 2026-10-12. Production now uses a verified halted pipeline
  restart and cooldown (transport.c); it is NOT seamless.

Usage:
  python kp_morph.py header             write main/kp_tables.h (the ladder)
  python kp_morph.py check              generator reproduces the U85Q LUTs and
                                        kp_tables.h is current
  python kp_morph.py study [out.json]   fields with a live kp change in them
Synthetic numbers (sim.py); not board timing, goggle acceptance or range.
"""
import json
import math
import os
import sys
from pathlib import Path
import numpy as np
from numba import njit

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sim  # noqa: E402

HEADER = HERE.parent / 'main' / 'kp_tables.h'
KP_LADDER = (0.85, 0.80, 0.75, 0.70, 0.65, 0.60, 0.55, 0.50)   # level 0 = U85Q
RANGE_MHZ = (-6.0, 9.0)
QUAD_KP = 0.5
ERASE_R = 0.8


def _nibble(word, positions):
    v = 0
    for bit in range(4):
        v |= ((word >> positions[bit]) & 1) << bit
    v = v - 16 if v > 7 else v
    return v + .5


def build_lut(kp, quad_kp=QUAD_KP):
    """U85Q LUT (layout 4411, 5 token bits, origin quadrant tokens, advance law)."""
    T, P = 32, 32
    bits = sim.PAIR_BITS
    ang = np.zeros(1024)
    rad = np.zeros(1024)
    for a in range(1024):
        word = 0
        for j in range(10):
            word |= ((a >> j) & 1) << int(bits[j])
        za = _nibble(word, (4, 5, 6, 7)) + 1j * _nibble(word, (0, 1, 2, 3))
        ang[a] = math.atan2(za.imag, za.real)
        rad[a] = abs(za)
    TA = T - 4
    tok = np.floor((ang + np.pi) * TA / (2 * np.pi)).astype(int) % TA
    org = rad < ERASE_R
    tok[org] = TA + (np.floor((ang + np.pi) / (np.pi / 2)).astype(int) % 4)[org]
    obs = (np.arange(TA) + .5) * 2 * np.pi / TA - np.pi
    ph = (np.arange(P) + .5) * 2 * np.pi / P - np.pi
    lo, hi = (2 * np.pi * f * 1e6 * 50e-9 for f in RANGE_MHZ)
    lut = np.zeros(1024, np.int64)
    for s in range(P):
        for t in range(T):
            if t >= TA:
                o = (t - TA + .5) * np.pi / 2 - np.pi
                e = (o - ph[s] + np.pi) % (2 * np.pi) - np.pi
                gain = quad_kp
            else:
                e = (obs[t] - ph[s] + np.pi) % (2 * np.pi) - np.pi
                gain = kp
            nxt = int(np.floor((ph[s] + gain * e + np.pi) * P / (2 * np.pi))) % P
            theta = (ph[nxt] - ph[s] + np.pi) % (2 * np.pi) - np.pi
            code = int(np.rint(np.clip((theta - lo) / (hi - lo) * 63, 0, 63)))
            lut[s * T + t] = code | (nxt << 6)
    lut |= tok.astype(np.int64) << 11
    return lut.astype(np.uint16)


def header_text():
    rows = []
    for kp in KP_LADDER:
        lut = build_lut(kp)
        body = ',\n'.join('    ' + ', '.join(f'0x{v:04x}' for v in lut[i:i + 12]) for i in range(0, 1024, 12))
        rows.append(f'    {{ /* kp {kp:.2f} */\n{body}\n    }}')
    kps = ', '.join(f'{int(round(kp * 100))}' for kp in KP_LADDER)
    return f"""/* C5VRX-5 by Twotoz and the C5VRX contributors: U85Q kp ladder.
 * Generated by research/kp_morph.py (the C5VRX-4 untrained U85Q formula of
 * PR #190); do not edit. Level 0 is the u85q.bsasm LUT bit-exactly; every
 * level keeps the same token bits and phase states. Production verifies the
 * entire halted LUT before a guarded pipeline restart (transport.c). */
#pragma once
#include <stdint.h>

#define KP_LEVELS {len(KP_LADDER)}
static const uint8_t kp_level_x100[KP_LEVELS] = {{{kps}}};
static const uint16_t kp_tables[KP_LEVELS][1024] = {{
{','.join(chr(10) + r for r in rows)[1:]}
}};
"""


def check():
    ok = True
    if not HEADER.exists() or HEADER.read_text() != header_text():
        print(f'{HEADER} is stale: run python kp_morph.py header')
        ok = False
    ref = json.loads((HERE / 'data' / 'tracker_luts.json').read_text())
    for name, entry in ref.items():
        got = build_lut(entry['params']['kp'], entry['params']['quad_kp'])
        same = np.array_equal(got, np.array(entry['lut'], np.uint16))
        ok &= same
        print(f'{name}: {"bit-exact" if same else "MISMATCH"} vs data/tracker_luts.json')
    for kp, f in ((0.85, 'u85q'), (0.6, 'u85q_kp060'), (0.5, 'u85q_kp050')):
        same = np.array_equal(build_lut(kp), sim.u85q_lut(HERE.parent / 'main' / f'{f}.bsasm'))
        ok &= same
        print(f'kp {kp}: {"bit-exact" if same else "MISMATCH"} vs main/{f}.bsasm')
    base = build_lut(KP_LADDER[0])
    for kp in KP_LADDER[1:]:
        lut = build_lut(kp)
        same_tokens = bool(np.all((lut >> 11) == (base >> 11)))
        ok &= same_tokens
        print(f'kp {KP_LADDER[0]:.2f} -> {kp:.2f}: token bits equal {same_tokens}, '
              f'{int(np.sum(lut != base))} of 1024 entries differ')
    return ok


@njit(cache=True)
def _codes_morph(raw, lut_a, lut_b, order, start, per_span):
    """U85Q over raw with LUT entries switched from lut_a to lut_b during the
    run: from span `start`, `per_span` more entries (in `order`) per span."""
    bits = np.array([4, 5, 6, 7, 0, 1, 2, 3, 15, 11], np.int64)
    lut = lut_a.copy()
    out = np.zeros(len(raw), np.uint8)
    state = 0
    written = 0.0
    done = 0
    for k in range(len(raw) // 2 - 1):
        if k >= start and done < len(order):
            written += per_span
            while done < len(order) and done < written:
                lut[order[done]] = lut_b[order[done]]
                done += 1
        word = np.int64(raw[2 * k]) | (np.int64(raw[2 * k + 1]) << 8)
        address = 0
        for j in range(10):
            address |= ((word >> bits[j]) & 1) << j
        token = np.int64(lut[address]) >> 11
        value = np.int64(lut[(state << 5) + token])
        state = (value >> 6) & 31
        out[2 * k + 2] = value & 63
        out[2 * k + 3] = value & 63
    return out


def _local_error(y, truth, lag, centre, half):
    """Mean squared video error in a window around `centre` (samples)."""
    a, b = max(centre - half, 0), min(centre + half, len(y) - lag)
    return float(np.mean((y[a + lag:b + lag] - truth[a:b]) ** 2))


def study(out_path=None):
    """One field per case. A live kp change starts mid-field; compare the
    video around the change with the same field decoded by each table alone
    (steady state), and the goggle sync over the whole field."""
    rows = []
    kp_pairs = ((0.85, 0.6), (0.6, 0.85), (0.85, 0.7), (0.7, 0.6))
    # Rewrite speeds: entries per 50 ns span. 1/20 = one register write per
    # us; 1/200 = one per 10 us (the whole change spread over ~8 ms).
    speeds = (1 / 20, 1 / 200)
    cnrs = [float(x) for x in os.environ.get('CNRS', '4,8,20').split(',')]
    for cnr in cnrs:
        for seed in (21, 22, 23, 24):
            std = ('PAL', 'NTSC')[seed % 2]
            c = sim.make_case(seed * 1000 + int(10 * cnr), cnr, std, 1.0, filter_hz=12e6, fields=1)
            n = len(c['raw'])
            start = n // 4
            for ka, kb in kp_pairs:
                la, lb = build_lut(ka), build_lut(kb)
                order = np.flatnonzero(la != lb).astype(np.int64)
                ya = sim.measure(c, sim.u85q_codes(c['raw'], la), sim.u85q_codes(c['clean'], la))
                yb = sim.measure(c, sim.u85q_codes(c['raw'], lb), sim.u85q_codes(c['clean'], lb))
                for speed in speeds:
                    codes = _codes_morph(c['raw'], la, lb, order, start, speed)
                    clean = _codes_morph(c['clean'], la, lb, order, start, speed)
                    m = sim.measure(c, codes, clean)
                    # Error right at the change vs both steady decodes, same window.
                    t = c['truth']
                    lag = int(np.argmax([np.dot(m['video'][3000 + L:23000 + L], t[3000:23000]) for L in range(60)]))
                    centre, half = 2 * start, 8000          # 0.2 ms either side of the first write
                    e_m = _local_error(m['video'], t, lag, centre, half)
                    e_a = _local_error(ya['video'], t, lag, centre, half)
                    e_b = _local_error(yb['video'], t, lag, centre, half)
                    row = dict(cnr=cnr, seed=seed, kp_from=ka, kp_to=kb, entries=len(order),
                               writes_per_span=speed, picture=m['picture'], picture_from=ya['picture'],
                               picture_to=yb['picture'], err_switch=e_m, err_from=e_a, err_to=e_b)
                    rows.append(row)
            print(f'C/N {cnr:4.1f} seed {seed} done', flush=True)
    summary = {}
    for r in rows:
        k = (r['cnr'], r['kp_from'], r['kp_to'], r['writes_per_span'])
        s = summary.setdefault(k, {'excess': [], 'pic': []})
        # Excess error at the change: above the worse of the two steady decodes.
        s['excess'].append(r['err_switch'] / max(r['err_from'], r['err_to']))
        s['pic'].append(r['picture'] - min(r['picture_from'], r['picture_to']))
    print('C/N  kp from->to  writes/span  error at change / worse steady   picture vs worse steady')
    for (cnr, a, b, sp), s in sorted(summary.items()):
        print(f'{cnr:4.1f}  {a:.2f}->{b:.2f}   {sp:9.5f}    {np.mean(s["excess"]):.3f} (max {np.max(s["excess"]):.3f})'
              f'                {np.mean(s["pic"]):+.4f}')
    if out_path:
        Path(out_path).write_text(json.dumps(rows, indent=1))
    return rows


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd == 'header':
        HEADER.write_text(header_text())
        print(f'wrote {HEADER}')
    elif cmd == 'check':
        sys.exit(0 if check() else 1)
    elif cmd == 'study':
        study(sys.argv[2] if len(sys.argv) > 2 else None)
    else:
        print(__doc__)
        sys.exit(2)
